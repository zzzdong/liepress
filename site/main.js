function createEditor() {
    const container = document.getElementById('monacoEditor');
    if (!container) return;

    editorInstance = monaco.editor.create(container, {
        value: DEFAULT_MARKDOWN,
        language: 'markdown',
        theme: 'liepress-light',
        fontSize: 14,
        fontFamily: "'JetBrains Mono', 'Fira Code', monospace",
        lineNumbers: 'on',
        minimap: { enabled: true, showSlider: 'mouseover' },
        automaticLayout: true,
        scrollBeyondLastLine: false,
        tabSize: 2,
        formatOnPaste: true,
        renderWhitespace: 'selection',
        wordWrap: 'on',
        guides: { indentation: true },
        padding: { top: 12, bottom: 12 },
        smoothScrolling: true,
        cursorBlinking: 'smooth',
        cursorSmoothCaretAnimation: 'on',
    });

    // Keyboard shortcut: Ctrl+Enter -> Render
    editorInstance.addCommand(monaco.KeyMod.CtrlCmd | monaco.KeyCode.Enter, function () {
        renderPdf();
    });
}

function getEditorValue() {
    return editorInstance ? editorInstance.getValue() : '';
}

function setEditorValue(value) {
    if (editorInstance) {
        editorInstance.setValue(value);
    }
}

// ── WASM ──────────────────────────────────────────────────

async function initWasm() {
    try {
        wasmModule = await import('./pkg/liepress_site.js');
        await wasmModule.default();
        console.log('WASM module loaded');
    } catch (err) {
        console.error('WASM load failed:', err);
        setStatus('WASM module failed to load');
        throw err;
    }
}

async function loadFonts() {
    const renderBtn = document.getElementById('render-pdf');

    for (const font of FONTS_TO_LOAD) {
        try {
            console.log('Loading font:', font.name, 'from', font.url);
            setStatus(`Loading font: ${font.name}...`);
            const response = await fetch(font.url);
            if (!response.ok) {
                throw new Error('HTTP ' + response.status);
            }
            const arrayBuffer = await response.arrayBuffer();
            const bytes = new Uint8Array(arrayBuffer);
            console.log('Font bytes loaded:', font.name, 'size:', bytes.length);

            // // 1. 以实际名称注册到 WASM（供 parley 通过 Named 名称查找）
            wasmModule.register_font_bytes(font.name, bytes);
            console.log('Font registered with WASM:', font.name);

            // 2. 以通用族名注册到 WASM（供 CSS generic family 关键字 serif/sans-serif/monospace 使用）
            //    同一个字体字节可以注册多次到不同名称下，parley 的 fontdb 会共享数据
            wasmModule.register_font_bytes(font.family, bytes);
            console.log('Font registered with WASM as generic family:', font.family);

            // 3. 注册到浏览器中（用于编辑器等 HTML 渲染）
            try {
                const fontFace = new FontFace(font.name, arrayBuffer);
                const loadedFont = await fontFace.load();
                document.fonts.add(loadedFont);
                console.log('Font loaded to browser:', font.name);
            } catch (browserErr) {
                console.warn('Browser font load failed:', font.name, browserErr);
            }
        } catch (err) {
            console.warn('Font load failed:', font.name, err);
        }
    }

    fontsReady = true;
    if (renderBtn) renderBtn.disabled = false;
    setStatus('Ready - fonts loaded');
    console.log('Font loading done');
}

// ── PDF Rendering ─────────────────────────────────────────

async function renderPdf() {
    if (!fontsReady) {
        setStatus('Fonts still loading...');
        return;
    }

    if (!wasmModule) {
        setStatus('WASM not loaded');
        return;
    }

    const markdown = getEditorValue().trim();
    if (!markdown) {
        setStatus('Please enter some Markdown');
        return;
    }

    setStatus('Rendering PDF...');

    try {
        console.log('Calling markdown_to_pdf_base64 with:', markdown.substring(0, 50) + '...');
        // 字体栈：显式指定具体字体名称，配合通用族名回退
        // 这里的 font-family 生成 body { font-family: ... }，正文用衬线/无衬线
        // 代码块不受影响（<pre>/<code> 有自己的 font-family: monospace, sans-serif）
        const fontFamily = [
            'Noto Serif', 'Noto Serif SC', 'Noto Serif CJK SC', 'serif',
            'Noto Sans', 'Noto Sans SC', 'Noto Sans CJK SC', 'sans-serif',
        ].join(', ');
        const base64 = wasmModule.markdown_to_pdf_base64(markdown, fontFamily, '');
        console.log('PDF generated, base64 length:', base64.length);
        currentPdfBase64 = base64;
        
        await displayPdf(base64);
        setStatus('PDF rendered successfully');
        
        // Enable download button
        const downloadBtn = document.getElementById('download-pdf');
        if (downloadBtn) {
            downloadBtn.disabled = false;
        }
    } catch (err) {
        console.error('PDF render error:', err);
        setStatus('Error: ' + err.message);
        showError('Failed to render PDF: ' + err.message);
    }
}

async function displayPdf(base64) {
    const pdfHost = document.getElementById('pdf-host');
    if (!pdfHost) return;

    // Clear previous content
    pdfHost.innerHTML = '';

    // Convert base64 to Uint8Array
    const binaryString = atob(base64);
    const bytes = new Uint8Array(binaryString.length);
    for (let i = 0; i < binaryString.length; i++) {
        bytes[i] = binaryString.charCodeAt(i);
    }

    // Load PDF with pdf.js
    const loadingTask = pdfjsLib.getDocument({ data: bytes });
    const pdf = await loadingTask.promise;

    // Render first page
    const page = await pdf.getPage(1);
    const scale = 1.5;
    const viewport = page.getViewport({ scale });

    const canvas = document.createElement('canvas');
    const context = canvas.getContext('2d');
    canvas.width = viewport.width;
    canvas.height = viewport.height;
    canvas.className = 'pdf-canvas';

    const renderContext = {
        canvasContext: context,
        viewport: viewport,
    };

    await page.render(renderContext).promise;
    pdfHost.appendChild(canvas);

    // Render additional pages
    for (let pageNum = 2; pageNum <= pdf.numPages; pageNum++) {
        const page = await pdf.getPage(pageNum);
        const viewport = page.getViewport({ scale });

        const canvas = document.createElement('canvas');
        const context = canvas.getContext('2d');
        canvas.width = viewport.width;
        canvas.height = viewport.height;
        canvas.className = 'pdf-canvas';

        const renderContext = {
            canvasContext: context,
            viewport: viewport,
        };

        await page.render(renderContext).promise;
        pdfHost.appendChild(canvas);
    }
}

function downloadPdf() {
    if (!currentPdfBase64) {
        showError('Please render a PDF first');
        return;
    }

    const binaryString = atob(currentPdfBase64);
    const bytes = new Uint8Array(binaryString.length);
    for (let i = 0; i < binaryString.length; i++) {
        bytes[i] = binaryString.charCodeAt(i);
    }

    const blob = new Blob([bytes], { type: 'application/pdf' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'document.pdf';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

// ── UI Helpers ────────────────────────────────────────────

function setStatus(message) {
    const statusEl = document.getElementById('status');
    if (statusEl) {
        statusEl.textContent = message;
    }
}

function showError(message) {
    const output = document.getElementById('output');
    if (output) {
        output.textContent = message;
        output.classList.remove('hidden');
    }
    setStatus('Error');
}

function hideError() {
    const output = document.getElementById('output');
    if (output) {
        output.classList.add('hidden');
    }
}

// ── Initialization ────────────────────────────────────────

document.addEventListener('DOMContentLoaded', function () {
    const renderBtn = document.getElementById('render-pdf');
    const downloadBtn = document.getElementById('download-pdf');

    if (renderBtn) {
        renderBtn.addEventListener('click', renderPdf);
        renderBtn.disabled = true;
    }

    if (downloadBtn) {
        downloadBtn.addEventListener('click', downloadPdf);
    }

    // Configure pdf.js worker
    if (typeof pdfjsLib !== 'undefined') {
        pdfjsLib.GlobalWorkerOptions.workerSrc = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js';
    }

    // Initialize WASM first, then load fonts
    initWasm().then(() => {
        return loadFonts();
    }).then(() => {
        console.log('Initialization complete');
    }).catch(err => {
        console.error('Initialization failed:', err);
        setStatus('Initialization failed');
    });
});
